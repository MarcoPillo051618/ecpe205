package com.ecpe308.sample;

public class Pet {
    private String name;
    private int age;

    // Accessor (getter) for name
    public String getName() {
        return name;
    }   

    // Mutator (setter) for name
    public void setName(String name) {
        this.name = name;
    }

    // Accessor (getter) for age
    public int getAge() {
        return age;
    }

    // Mutator (setter) for age
    public void setAge(int age) {
        this.age = age;
    }
}
